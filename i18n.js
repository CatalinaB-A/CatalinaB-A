  const root = document.documentElement;
  let stored = null;
  try { stored = localStorage.getItem(LANG_KEY); } catch { /* almacenamiento bloqueado */ }
  let lang = LANGS.includes(stored) ? stored : 'es';

  const t = (key, vars) => {
    let value = DICT[lang]?.[key] ?? DICT.es[key] ?? key;
    if (vars) {
      value = value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] ?? match));
    }
    return value;
  };

  const updateToggles = () => {
    document.querySelectorAll('[data-lang-toggle]').forEach(button => {
      const code = button.querySelector('.lang-code');
      if (code) code.textContent = CODES[lang];
      button.setAttribute('aria-label', t('a11y.lang'));
      button.title = `${NAMES[lang]} → ${NAMES[LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]]}`;
    });
  };

  const apply = (scope = document) => {
    scope.querySelectorAll('[data-i18n]').forEach(node => {
      node.textContent = t(node.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(node => {
      node.innerHTML = t(node.dataset.i18nHtml);
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(node => {
      node.setAttribute('aria-label', t(node.dataset.i18nAria));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
      node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
    });
    scope.querySelectorAll('[data-i18n-content]').forEach(node => {
      node.setAttribute('content', t(node.dataset.i18nContent));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(node => {
      node.setAttribute('title', t(node.dataset.i18nTitle));
    });
    root.lang = lang === 'zh' ? 'zh-CN' : lang;
    updateToggles();
  };

  const setLang = next => {
    if (!LANGS.includes(next)) return;
    lang = next;
    try { localStorage.setItem(LANG_KEY, lang); } catch { /* sesión */ }
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  };

  const cycle = () => setLang(LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]);

  document.addEventListener('click', event => {
    const button = event.target.closest('[data-lang-toggle]');
    if (button) cycle();
  });

  window.i18n = {
    t,
    apply,
    setLang,
    cycle,
    LANGS,
    get lang() { return lang; }
  };

  apply();
  document.addEventListener('DOMContentLoaded', () => apply());
